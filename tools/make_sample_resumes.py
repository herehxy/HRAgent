TEMPLATE = """姓名：{name}
性别：{gender}
手机：{phone}
邮箱：{email}
现单位：{org}
专业：{major}
求职意向：{intent}

教育背景
{edu}

工作经历
{job}
{duties}

专业技能
{skills}

证书
{certs}
"""


def _render(s: dict) -> str:
    edu = "\n".join(s["edu"]) if s["edu"] else "（无）"
    duties = "\n".join(f"· {d}" for d in s["duties"])
    # 技能栏把正文里出现过的能力词再列一遍：抽取看的是**全文命中**，
    # 这里再列一次只是让"这个人擅长什么"在简历上一眼可见（与真实简历一致）。
    skills = "\n".join(f"· {x}" for x in s["skills"])
    certs = "、".join(s["certs"]) if s["certs"] else "（无）"
    return TEMPLATE.format(
        name=s["name"], gender=s["gender"], phone=s["phone"], email=s["email"],
        org=s["org"], major=s["major"] or "（简历未填写）",
        # 求职意向只留岗位名：年限写成"（6 年工作经验）"之后，
        # 放进求职意向行会读成"求职意向：高级研究员（6 年工作经验）"，很别扭。
        # 年限由工作经历那行承担，抽取照样能认（显式年限优先于按年份推算）。
        intent=re.sub(r"（[^）]*）", "", s.get("job", "").split("·")[-1]).strip() or "（面议）",
        edu=edu, job=s["job"], duties=duties, skills=skills, certs=certs,
    )


def main() -> int:
    ap = argparse.ArgumentParser(description="生成文本简历样例")
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    for s in SAMPLES:
        # 专业留空的样例：`专业：` 那一行不能出现，否则会抽出"（简历未填写）"这种假专业
        text = _render(s)
        if not s["major"]:
            text = "\n".join(
                ln for ln in text.split("\n") if not ln.startswith("专业：")
            )
        path = os.path.join(args.out, s["file"])
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"[√] {s['file']}")
    print(f"\n共 {len(SAMPLES)} 份样例 → {args.out}")
    print("[i] 导入：python cli.py ingest --folder data/resumes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

_SUFFIXES = re.compile(r"[（(][^（）()]*[)）]|[ \t　]")


def normalize_school(name: str | None) -> str:
    """校名归一：去空白、去（北京）（深圳）等括号后缀。

    分校/学部的**非括号**后缀（秦皇岛分校、医学部）由 `school_tier` 的
    逐级剥后缀重试兜住，这里不做——避免把"XX学院"这类独立院校错并进本部。
    """
    return _SUFFIXES.sub("", (name or "").strip())


def school_tier(name: str | None) -> str | None:
    """返回 "985" / "211" / None。985 优先于 211 返回。"""
    s = normalize_school(name)
    if not s:
        return None
    if s in _985:
        return "985"
    if s in _211_only:
        return "211"
    # 非括号后缀逐级剥掉重试：东北大学秦皇岛分校 → 东北大学；北京大学医学部 → 北京大学
    for suf in ("秦皇岛分校", "盘锦校区", "威海校区", "珠海校区", "苏州校区", "医学部", "分校"):
        if s.endswith(suf) and len(s) > len(suf) + 2:
            s2 = s[: -len(suf)]
            if s2 in _985:
                return "985"
            if s2 in _211_only:
                return "211"
    return None


def matches_tier(name: str | None, want: str) -> bool:
    """筛选判定：want="985" 只认 985；want="211" 认 985 + 211（985 全部属于 211）。"""
    t = school_tier(name)
    if want == "985":
        return t == "985"
    if want == "211":
        return t in ("985", "211")
    return False
